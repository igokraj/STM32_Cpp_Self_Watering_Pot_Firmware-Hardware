#define SSD1306_DATA  0x40

// A full 1 KB frame at 100 kHz takes ~92 ms, so the data transfer needs a longer
// timeout than single commands. Both are kept short enough that a missing display
// cannot stall init() past the ~2 s watchdog window.
#define I2C_CMD_TIMEOUT   50
#define I2C_DATA_TIMEOUT  250

